package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"
	"strconv"
	"strings"
)

func generateTypeScript(schemaBytes []byte) ([]byte, error) {
	var document map[string]any
	if err := json.Unmarshal(schemaBytes, &document); err != nil {
		return nil, err
	}
	defs, _ := document["$defs"].(map[string]any)
	enums, _ := document["x-enums"].(map[string]any)
	if defs == nil || enums == nil {
		return nil, fmt.Errorf("schema is missing generated definitions or enums")
	}
	enumNames := make([]string, 0, len(enums))
	for name := range enums {
		enumNames = append(enumNames, name)
	}
	sort.Strings(enumNames)
	enumAliases := map[string]string{}
	var out bytes.Buffer
	out.WriteString("// Code generated by cmd/contractgen; DO NOT EDIT.\n\n")
	for _, name := range enumNames {
		values, ok := enums[name].([]any)
		if !ok {
			return nil, fmt.Errorf("enum %s is not a string array", name)
		}
		parts := make([]string, 0, len(values))
		for _, value := range values {
			text, ok := value.(string)
			if !ok {
				return nil, fmt.Errorf("enum %s has a non-string value", name)
			}
			parts = append(parts, strconv.Quote(text))
		}
		sort.Strings(parts)
		enumAliases[strings.Join(parts, "|")] = name
		fmt.Fprintf(&out, "export type %s = %s;\n", name, strings.Join(parts, " | "))
	}
	if len(enumNames) > 0 {
		out.WriteByte('\n')
	}
	defNames := make([]string, 0, len(defs))
	for name := range defs {
		defNames = append(defNames, name)
	}
	sort.Strings(defNames)
	for _, name := range defNames {
		s, ok := defs[name].(map[string]any)
		if !ok {
			return nil, fmt.Errorf("definition %s is not a schema object", name)
		}
		if branches, ok := s["oneOf"].([]any); ok {
			branchTypes := make([]string, 0, len(branches))
			for _, branch := range branches {
				branchSchema, ok := branch.(map[string]any)
				if !ok {
					return nil, fmt.Errorf("definition %s has an invalid oneOf branch", name)
				}
				typeName, err := schemaType(branchSchema, enumAliases)
				if err != nil {
					return nil, fmt.Errorf("definition %s oneOf: %w", name, err)
				}
				branchTypes = append(branchTypes, typeName)
			}
			fmt.Fprintf(&out, "export type %s = %s;\n\n", name, strings.Join(branchTypes, " | "))
			continue
		}
		if s["type"] != "object" {
			continue
		}
		props, _ := s["properties"].(map[string]any)
		required := stringSet(s["required"])
		fmt.Fprintf(&out, "export interface %s {\n", name)
		propNames := make([]string, 0, len(props))
		for field := range props {
			propNames = append(propNames, field)
		}
		sort.Strings(propNames)
		for _, field := range propNames {
			fieldSchema, ok := props[field].(map[string]any)
			if !ok {
				return nil, fmt.Errorf("%s.%s schema is invalid", name, field)
			}
			tsType, err := schemaType(fieldSchema, enumAliases)
			if err != nil {
				return nil, fmt.Errorf("%s.%s: %w", name, field, err)
			}
			optional := ""
			if !required[field] {
				optional = "?"
			}
			fmt.Fprintf(&out, "  %s%s: %s;\n", strconv.Quote(field), optional, tsType)
		}
		out.WriteString("}\n\n")
	}
	encoded, err := json.Marshal(document)
	if err != nil {
		return nil, err
	}
	fmt.Fprintf(&out, `type ContractSchema = { $defs: Record<string, ContractSchema>; properties?: Record<string, ContractSchema>; propertyNames?: ContractSchema; required?: string[]; items?: ContractSchema; additionalProperties?: boolean | ContractSchema; enum?: unknown[]; oneOf?: ContractSchema[]; anyOf?: ContractSchema[]; const?: unknown; type?: string; format?: string; pattern?: string; minimum?: number; maximum?: number; minLength?: number; maxLength?: number; minItems?: number; maxItems?: number; [key: string]: unknown };
const contractSchema = JSON.parse(%s) as ContractSchema;

function isJSONValue(value: unknown, depth = 0): boolean {
  if (depth > 64) return false;
  if (value === null || typeof value === "string" || typeof value === "boolean") return true;
  if (typeof value === "number") return Number.isFinite(value);
  if (Array.isArray(value)) return value.every((item) => isJSONValue(item, depth + 1));
  if (typeof value !== "object") return false;
  const prototype = Object.getPrototypeOf(value);
  if (prototype !== Object.prototype && prototype !== null) return false;
  return Object.values(value as Record<string, unknown>).every((item) => isJSONValue(item, depth + 1));
}

function matches(schema: ContractSchema, value: unknown, depth = 0): boolean {
  if (depth > 64) return false;
  if (schema["x-open-json-value"] === true) return isJSONValue(value) && (typeof schema["x-max-json-bytes"] !== "number" || new TextEncoder().encode(JSON.stringify(value)).length <= schema["x-max-json-bytes"]);
  if (schema.const !== undefined && value !== schema.const) return false;
  if (Array.isArray(schema.oneOf)) return schema.oneOf.filter((branch) => matches(branch, value, depth + 1)).length === 1;
  if (Array.isArray(schema.anyOf)) return schema.anyOf.some((branch) => matches(branch, value, depth + 1));
  if (typeof schema.$ref === "string") {
    const name = schema.$ref.replace("#/$defs/", "");
    const target = contractSchema.$defs[name];
    return target !== undefined && matches(target, value, depth + 1);
  }
  if (Array.isArray(schema.enum) && !schema.enum.some((entry) => entry === value)) return false;
  if (schema.type === "string") {
    if (typeof value !== "string") return false;
    if (schema.minLength !== undefined && [...value].length < schema.minLength) return false;
    if (schema.maxLength !== undefined && [...value].length > schema.maxLength) return false;
    if (schema.pattern !== undefined && !new RegExp(schema.pattern).test(value)) return false;
    if (typeof schema["x-max-utf8-bytes"] === "number" && new TextEncoder().encode(value).length > schema["x-max-utf8-bytes"]) return false;
    return schema.format !== "date-time" || Number.isFinite(Date.parse(value));
  }
  if (schema.type === "boolean") return typeof value === "boolean";
  if (schema.type === "integer") return typeof value === "number" && Number.isInteger(value) && (schema.minimum === undefined || value >= schema.minimum) && (schema.maximum === undefined || value <= schema.maximum);
  if (schema.type === "number") return typeof value === "number" && Number.isFinite(value);
  if (schema.type === "array") return Array.isArray(value) && schema.items !== undefined && (schema.minItems === undefined || value.length >= schema.minItems) && (schema.maxItems === undefined || value.length <= schema.maxItems) && value.every((entry) => matches(schema.items!, entry, depth + 1));
  if (schema.type === "object") {
    if (value === null || typeof value !== "object" || Array.isArray(value)) return false;
    const prototype = Object.getPrototypeOf(value);
    if (prototype !== Object.prototype && prototype !== null) return false;
    const record = value as Record<string, unknown>;
    if (schema.required?.some((key) => !Object.prototype.hasOwnProperty.call(record, key))) return false;
    const properties = schema.properties ?? {};
    for (const [key, entry] of Object.entries(record)) {
      if (schema.propertyNames !== undefined && !matches(schema.propertyNames, key, depth + 1)) return false;
      const child = properties[key];
      if (child !== undefined) { if (!matches(child, entry, depth + 1)) return false; continue; }
      if (schema.additionalProperties === false) return false;
      if (schema.additionalProperties && typeof schema.additionalProperties === "object" && !matches(schema.additionalProperties, entry, depth + 1)) return false;
    }
    return true;
  }
  return isJSONValue(value);
}

export function decodeContract<T>(name: string, value: unknown): T {
  const schema = contractSchema.properties?.[name];
  if (schema === undefined || !matches(schema, value)) throw new TypeError("Invalid Kora contract: " + name);
  return value as T;
}

export function isContract<T>(name: string, value: unknown): value is T {
  const schema = contractSchema.properties?.[name];
  return schema !== undefined && matches(schema, value);
}
`, strconv.Quote(string(encoded)))
	return out.Bytes(), nil
}

func stringSet(value any) map[string]bool {
	set := map[string]bool{}
	if values, ok := value.([]any); ok {
		for _, entry := range values {
			if name, ok := entry.(string); ok {
				set[name] = true
			}
		}
	}
	return set
}

func schemaType(schema map[string]any, enumAliases map[string]string) (string, error) {
	if schema["x-open-json-value"] == true {
		return "unknown", nil
	}
	if value, ok := schema["const"].(string); ok {
		return strconv.Quote(value), nil
	}
	if ref, ok := schema["$ref"].(string); ok {
		return strings.TrimPrefix(ref, "#/$defs/"), nil
	}
	if values, ok := schema["enum"].([]any); ok {
		encoded := make([]string, 0, len(values))
		for _, value := range values {
			text, ok := value.(string)
			if !ok {
				return "", fmt.Errorf("unsupported enum value")
			}
			encoded = append(encoded, strconv.Quote(text))
		}
		sort.Strings(encoded)
		if alias, ok := enumAliases[strings.Join(encoded, "|")]; ok {
			return alias, nil
		}
		return strings.Join(encoded, " | "), nil
	}
	switch schema["type"] {
	case "string":
		return "string", nil
	case "boolean":
		return "boolean", nil
	case "integer", "number":
		return "number", nil
	case "array":
		items, ok := schema["items"].(map[string]any)
		if !ok {
			return "", fmt.Errorf("array items missing")
		}
		item, err := schemaType(items, enumAliases)
		return "Array<" + item + ">", err
	case "object":
		if props, ok := schema["properties"].(map[string]any); ok {
			required := stringSet(schema["required"])
			names := make([]string, 0, len(props))
			for name := range props {
				names = append(names, name)
			}
			sort.Strings(names)
			parts := make([]string, 0, len(names))
			for _, name := range names {
				child, ok := props[name].(map[string]any)
				if !ok {
					return "", fmt.Errorf("property %s is invalid", name)
				}
				childType, err := schemaType(child, enumAliases)
				if err != nil {
					return "", err
				}
				optional := ""
				if !required[name] {
					optional = "?"
				}
				parts = append(parts, strconv.Quote(name)+optional+": "+childType)
			}
			return "{ " + strings.Join(parts, "; ") + " }", nil
		}
		if keySchema, ok := schema["propertyNames"].(map[string]any); ok {
			keyType, err := schemaType(keySchema, enumAliases)
			if err != nil {
				return "", err
			}
			valueSchema, ok := schema["additionalProperties"].(map[string]any)
			if !ok {
				return "", fmt.Errorf("enum-keyed map value schema is missing")
			}
			valueType, err := schemaType(valueSchema, enumAliases)
			return "Partial<Record<" + keyType + ", " + valueType + ">>", err
		}
		if additional, ok := schema["additionalProperties"].(map[string]any); ok {
			value, err := schemaType(additional, enumAliases)
			return "Record<string, " + value + ">", err
		}
		if schema["additionalProperties"] == true {
			return "Record<string, unknown>", nil
		}
		return "Record<string, unknown>", nil
	default:
		return "", fmt.Errorf("unsupported schema type %v", schema["type"])
	}
}
