#!/usr/bin/env python3
"""Copy generated Engine v2 validators and refresh their source manifests."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
from datetime import date


ENGINE = Path(__file__).resolve().parents[1]
PROJECTS = Path(os.environ.get("KORA_PROJECTS_ROOT", ENGINE.parent)).resolve()
CONSUMERS = {
    "kora-studio-mvp/src/generated/engine-v2.ts": PROJECTS / "kora-studio-mvp/src/generated/engine-v2.ts",
    "kora-ts-sdk/src/generated/engine-v2.ts": PROJECTS / "kora-ts-sdk/src/generated/engine-v2.ts",
}
ANDROID = PROJECTS / "kora-mobile"
ANDROID_SCHEMA = ANDROID / "app/src/main/assets/contracts/engine-v2.json"
ANDROID_MANIFEST = ANDROID / "app/src/main/java/com/kora/mobile/generated/EngineContractManifest.kt"
CLOUD_MANIFEST = PROJECTS / "kora-cloud/contract-fixtures/engine-v2-manifest.json"
MANIFESTS = (
    PROJECTS / "kora-studio-mvp/src/generated/engine-v2.manifest.ts",
    PROJECTS / "kora-ts-sdk/src/generated/manifest.ts",
)
FIXTURE_MANIFEST = ENGINE / "docs/architecture/contract-fixture-manifest.json"
SOURCE_TYPESCRIPT = ENGINE / "contract/generated/engine-v2.ts"
SOURCE_SCHEMA = ENGINE / "contract/schema/engine-v2.json"


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def source_revision(engine: Path = ENGINE) -> tuple[str, str]:
    contract_inputs = [
        ":(glob)contract/**/*.go",
        "contract/generated/engine-v2.ts",
        "contract/schema/engine-v2.json",
    ]
    revision = subprocess.run(
        ["git", "log", "-1", "--format=%H", "--", *contract_inputs], cwd=engine, check=True,
        capture_output=True, text=True,
    ).stdout.strip()
    dirty = subprocess.run(
        ["git", "status", "--porcelain", "--untracked-files=all", "--", *contract_inputs], cwd=engine, check=True,
        capture_output=True, text=True,
    ).stdout
    return revision, "uncommitted" if dirty else "clean"


def render_manifest(revision: str, source_tree: str, artifact_hash: str, schema_hash: str) -> bytes:
    text = (
        "// This manifest pins the Engine source revision and bytes used to generate\n"
        "// engine-v2.ts. Regenerate it only when the Engine contract artifact changes.\n"
        "export const ENGINE_CONTRACT_MANIFEST = {\n"
        "  schemaVersion: 2,\n"
        f"  sourceRevision: '{revision}',\n"
        f"  sourceTree: '{source_tree}',\n"
        "  artifact: 'contract/generated/engine-v2.ts',\n"
        f"  artifactSHA256: '{artifact_hash}',\n"
        f"  schemaSHA256: '{schema_hash}',\n"
        "} as const\n"
    )
    return text.encode("utf-8")


def render_android_manifest(revision: str, source_tree: str, schema_hash: str) -> bytes:
    text = (
        "// Generated by kora/scripts/sync-contract-consumers.py; DO NOT EDIT.\n"
        "package com.kora.mobile.generated\n\n"
        "object EngineContractManifest {\n"
        "    const val schemaVersion = 2\n"
        f'    const val sourceRevision = "{revision}"\n'
        f'    const val sourceTree = "{source_tree}"\n'
        '    const val artifact = "app/src/main/assets/contracts/engine-v2.json"\n'
        f'    const val schemaSHA256 = "{schema_hash}"\n'
        "}\n"
    )
    return text.encode("utf-8")


def render_cloud_manifest(revision: str, source_tree: str, artifact_hash: str, schema_hash: str) -> bytes:
    document = {
        "schema_version": 2,
        "source_revision": revision,
        "source_tree": source_tree,
        "schema": "kora/contract/schema/engine-v2.json",
        "schema_sha256": schema_hash,
        "typescript": "kora/contract/generated/engine-v2.ts",
        "typescript_sha256": artifact_hash,
    }
    return (json.dumps(document, indent=2) + "\n").encode("utf-8")


def expected_files(update_snapshot_date: bool) -> dict[Path, bytes]:
    source = SOURCE_TYPESCRIPT.read_bytes()
    artifact_hash = sha256(source)
    revision, source_tree = source_revision()
    files = {path: source for path in CONSUMERS.values()}
    schema = SOURCE_SCHEMA.read_bytes()
    schema_hash = sha256(schema)
    manifest = render_manifest(revision, source_tree, artifact_hash, schema_hash)
    files.update({path: manifest for path in MANIFESTS})
    cloud_manifest = render_cloud_manifest(revision, source_tree, artifact_hash, schema_hash)
    files[CLOUD_MANIFEST] = cloud_manifest
    files[ANDROID_SCHEMA] = schema
    android_manifest = render_android_manifest(revision, source_tree, schema_hash)
    files[ANDROID_MANIFEST] = android_manifest

    fixture_manifest = json.loads(FIXTURE_MANIFEST.read_text(encoding="utf-8"))
    if update_snapshot_date:
        fixture_manifest["snapshot_date"] = date.today().isoformat()
    for fixture in fixture_manifest["fixtures"]:
        source_fixture = ENGINE / "contract-fixtures" / f"{fixture['name']}.json"
        contents = source_fixture.read_bytes()
        if sha256(contents) != fixture["sha256"]:
            raise ValueError(f"fixture digest does not match manifest: {source_fixture}")
        for consumer in fixture["consumers"]:
            repository, _, relative = consumer.partition("/")
            if repository not in {"kora", "kora-cloud", "kora-studio-mvp", "kora-ts-sdk", "kora-mobile-app"} or not relative:
                raise ValueError(f"invalid fixture consumer path: {consumer}")
            if repository == "kora":
                destination = ENGINE / relative
            else:
                local_repository = "kora-mobile" if repository == "kora-mobile-app" else repository
                destination = PROJECTS / local_repository / relative
            files[destination] = contents
    consumer_fields = {
        "studio_copy": "kora-studio-mvp/src/generated/engine-v2.ts",
        "sdk_copy": "kora-ts-sdk/src/generated/engine-v2.ts",
    }
    for contract_entry in fixture_manifest["engine_contracts"]:
        version = contract_entry["version"]
        schema_path = ENGINE / f"contract/schema/engine-{version}.json"
        typescript_path = ENGINE / f"contract/generated/engine-{version}.ts"
        contract_entry["schema_sha256"] = sha256(schema_path.read_bytes())
        contract_entry["typescript_sha256"] = sha256(typescript_path.read_bytes())
        if version != "v2":
            continue
        contract_entry["schema_sha256"] = schema_hash
        contract_entry["typescript_sha256"] = artifact_hash
        for field, manifest_path in consumer_fields.items():
            contract_entry[field] = manifest_path
            contract_entry[f"{field}_sha256"] = artifact_hash
        contract_entry["android_schema"] = "kora-mobile-app/app/src/main/assets/contracts/engine-v2.json"
        contract_entry["android_schema_sha256"] = schema_hash
        contract_entry["android_manifest"] = "kora-mobile-app/app/src/main/java/com/kora/mobile/generated/EngineContractManifest.kt"
        contract_entry["android_manifest_sha256"] = sha256(android_manifest)
        contract_entry["cloud_manifest"] = "kora-cloud/contract-fixtures/engine-v2-manifest.json"
        contract_entry["cloud_manifest_sha256"] = sha256(cloud_manifest)
    files[FIXTURE_MANIFEST] = (json.dumps(fixture_manifest, indent=2) + "\n").encode("utf-8")
    return files


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail instead of writing drifted files")
    args = parser.parse_args()
    files = expected_files(update_snapshot_date=not args.check)
    stale = []
    for path, expected in files.items():
        try:
            current = path.read_bytes()
        except OSError:
            current = None
        if current == expected:
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)
    if args.check and stale:
        for path in stale:
            print(f"generated Engine contract consumer is stale: {path}", file=sys.stderr)
        print("run `make sync-contracts` from a checkout with all first-party repositories", file=sys.stderr)
        return 1
    if stale:
        print("synchronized generated Engine v2 consumers and manifests")
    else:
        print("Engine v2 contract copies and manifests are current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
